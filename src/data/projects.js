/**
 * Returns a flat list of all images across all categories,
 * each enriched with its parent category metadata.
 */
export function getAllImages() {
  return categories.flatMap((cat) =>
    cat.images.map((img) => ({
      ...img,
      categoryId: cat.id,
      categoryLabel: cat.label,
      categoryColor: cat.color,
    }))
  );
}
